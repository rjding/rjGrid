export const RJ_PRESETS: Record<RjLang, RjMessages> = { zh: zhCN, en: { ...zhCN, ...enUS } }

/** 归一语言标识：zh-CN/zh_TW/en-US/en 等 → 'zh' | 'en' */
export function normalizeLang(lang?: string): RjLang {
  if (!lang) return 'zh'
  const l = String(lang).toLowerCase()
  return l.startsWith('en') ? 'en' : 'zh'
}

/** 解析最终文案表：预设底 + 局部覆盖（override 优先级最高） */
export function resolveMessages(lang?: string, override?: RjMessages | null): RjMessages {
  const base = RJ_PRESETS[normalizeLang(lang)]
  if (!override) return base
  return { ...base, ...override }
}

/** 插值：把 {key} 替换为 params[key] */
export function interpolate(str: string, params?: Record<string, string | number>): string {
  if (!params) return str
  let out = str
  for (const k of Object.keys(params)) out = out.split('{' + k + '}').join(String(params[k]))
  return out
}

/** 翻译查表：命中返回并插值，未命中返回 key 本身（便于发现漏译） */
export function translate(
  messages: RjMessages,
  key: string,
  params?: Record<string, string | number>
): string {
  const s = messages[key] != null ? messages[key] : key
  return interpolate(s, params)
}

export type RjTranslate = (key: string, params?: Record<string, string | number>) => string

/** 注入键：网格根 provide 翻译函数，子组件 inject 消费 */
export const RJ_LOCALE_KEY: InjectionKey<RjTranslate> = Symbol('rj-locale')

/** 子组件默认翻译函数（未 inject 到时回退，避免单独使用时崩溃） */
export const defaultTranslate: RjTranslate = (key, params) =>
  interpolate(zhCN[key] != null ? zhCN[key] : key, params)
